  species_area_table,
  Species,
  method,
  ssp,
  period
)

fwrite(
  ecosystem_area_table,
  file.path(
    table_dir,
    "future_ecosystem_area_var.csv"
  )
)

fwrite(
  transition_table,
  file.path(
    table_dir,
    "future_ecosystem_transition_var.csv"
